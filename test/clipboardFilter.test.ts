import { describe, it, expect } from 'vitest';
import { isPrivateClipboard } from '../src/core/clipboardFilter';

const raw = (f: string) => `electron application/osclipboard;format="${f}"`;

describe('isPrivateClipboard', () => {
  it('skips content password managers mark as concealed or transient on macOS', () => {
    expect(isPrivateClipboard(['text/plain', raw('org.nspasteboard.ConcealedType')])).toBe(true);
    expect(isPrivateClipboard(['text/plain', raw('org.nspasteboard.TransientType')])).toBe(true);
    expect(isPrivateClipboard(['text/plain', raw('org.nspasteboard.AutoGeneratedType')])).toBe(true);
  });

  it('skips content excluded from clipboard monitoring on Windows', () => {
    expect(isPrivateClipboard(['text/plain', raw('ExcludeClipboardContentFromMonitorProcessing')])).toBe(true);
    expect(isPrivateClipboard(['text/plain', raw('CanIncludeInClipboardHistory')])).toBe(true);
  });

  it('keeps ordinary content', () => {
    expect(isPrivateClipboard(['text/plain', raw('public.utf8-plain-text')])).toBe(false);
    expect(isPrivateClipboard([])).toBe(false);
  });
});
